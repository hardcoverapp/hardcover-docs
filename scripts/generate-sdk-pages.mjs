#!/usr/bin/env node
// Writes one docs page per SDK resource, from the SDK's method catalog
// (src/components/SdkExplorer/catalog.json, synced by `npm run sync:sdk-catalog`).
// Each method gets its signature, summary, parameters and a live explorer.
//
//   npm run generate:sdk-pages
//
// The pages are generated: change the catalog (in the SDK repo) or this
// script, not the .mdx files.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";

const catalog = JSON.parse(readFileSync("src/components/SdkExplorer/catalog.json", "utf8"));
const dir = "src/content/docs/sdk/typescript/resources";

// Start clean, so a resource removed from the SDK loses its page too.
rmSync(dir, { recursive: true, force: true });
mkdirSync(dir, { recursive: true });

const title = (name) => name[0].toUpperCase() + name.slice(1);

// Catalog text as MDX prose. MDX reads { } as JavaScript and < as the start of
// a component, so escape them outside inline code (`…` is already literal).
function text(value) {
  return String(value ?? "")
    .split(/(`[^`]*`)/)
    .map((part) => (part.startsWith("`") ? part : part.replace(/[{}]/g, (brace) => `\\${brace}`).replace(/</g, "&lt;")))
    .join("");
}

// "hc.library.add(bookId, options?)" or "readingStats(hc, period)".
function signature(resource, method) {
  const params = method.params.map((param) => (param.required ? param.name : `${param.name}?`));

  if (resource.call === "function") return `${method.name}(${["hc", ...params].join(", ")})`;
  return `hc.${resource.name}.${method.name}(${params.join(", ")})`;
}

// A param's type, as a reader would think of it.
function typeOf(param) {
  switch (param.kind) {
    case "enum":
      return param.values ? `${param.enum} (${param.values.join(", ")})` : param.enum;
    case "literal":
      return param.values.map((value) => `"${value}"`).join(" \\| ");
    case "lines":
      return param.itemKind === "number" ? "number[]" : "string[]";
    case "longText":
    case "text":
      return "string";
    case "date":
      return "date (YYYY-MM-DD)";
    case "datetime":
      return "Date or ISO string";
    case "options":
      return "object";
    case "json":
      return "object (see example)";
    case "period":
      return "period";
    default:
      return param.kind;
  }
}

const cell = (value) => text(value).replace(/\|/g, "\\|").replace(/\n/g, " ");

// Every param, with an options object's fields listed as options.field.
function rows(params, prefix = "") {
  return params.flatMap((param) => {
    const name = prefix + param.name;
    const row = `| \`${name}\` | ${cell(typeOf(param))} | ${param.required ? "yes" : ""} | ${cell(param.hint ?? (param.kind === "options" ? "Only the fields you set are sent." : param.label))} |`;

    return param.kind === "options" ? [row, ...rows(param.fields ?? [], `${name}.`)] : [row];
  });
}

for (const resource of catalog.resources) {
  const lines = [
    "---",
    `title: ${title(resource.name)}`,
    `description: ${JSON.stringify(resource.summary)}`,
    "layout: /src/layouts/documentation.astro",
    "---",
    "",
    "{/* Generated by scripts/generate-sdk-pages.mjs from the SDK catalog. Don't edit by hand. */}",
    "",
    "import SdkExplorer from '@/components/SdkExplorer/SdkExplorer.astro';",
    "",
    text(resource.summary),
    "",
  ];

  if (resource.call === "function") {
    lines.push(`Import from \`${resource.module}\`: these are functions that take the client first.`, "");
  }

  for (const method of resource.methods) {
    lines.push(
      `## ${method.name}`,
      "",
      `\`${signature(resource, method)}\``,
      "",
      text(method.summary),
      "",
    );

    const notes = [];
    if (method.scopes.length) notes.push(`**Scopes:** ${method.scopes.map((scope) => `\`${scope}\``).join(", ")}`);
    if (method.destructive) notes.push("**Deletes data.** The explorer previews the request without sending it.");
    else if (method.writes) notes.push("**Changes data.** The explorer previews the request without sending it.");
    if (notes.length) lines.push(notes.join(" · "), "");

    if (method.params.length) {
      lines.push("| Parameter | Type | Required | Notes |", "|---|---|---|---|", ...rows(method.params), "");
    }

    lines.push(`<SdkExplorer method="${resource.name}.${method.name}" compact />`, "");
  }

  writeFileSync(`${dir}/${title(resource.name)}.mdx`, lines.join("\n"));
}

console.log(`Wrote ${catalog.resources.length} pages to ${dir}`);
