#!/usr/bin/env node
// Writes the TypeScript SDK's generated pages:
//   - one page per resource for each documented minor version, from that
//     version's catalog (src/components/SdkExplorer/catalogs/0.1.json), with
//     each method's signature, summary, scopes, parameters and a live explorer
//   - the changelog page, from the SDK's CHANGELOG.md
// Both are synced from the SDK repo by `npm run sync:sdk-catalog`.
//
//   npm run generate:sdk-pages
//
// The pages are generated: change the catalog or changelog (in the SDK repo)
// or this script, not the .mdx files. Each version's overview and getting
// started pages are written by hand.
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";

const root = "src/content/docs/sdk/typescript";
const catalogs = "src/components/SdkExplorer/catalogs";

const title = (name) => name[0].toUpperCase() + name.slice(1);

// Catalog text as MDX prose. MDX reads { } as JavaScript and < as the start of
// a component, so escape them outside inline code (`…` is already literal).
function text(value) {
  return String(value ?? "")
    .split(/(`[^`]*`)/)
    .map((part) => (part.startsWith("`") ? part : part.replace(/[{}]/g, (brace) => `\\${brace}`).replace(/</g, "&lt;")))
    .join("");
}

// "hc.library.add(bookId, options?)" or "readingStats(hc, period)".
function signature(resource, method) {
  const params = method.params.map((param) => (param.required ? param.name : `${param.name}?`));

  if (resource.call === "function") return `${method.name}(${["hc", ...params].join(", ")})`;
  return `hc.${resource.name}.${method.name}(${params.join(", ")})`;
}

// A param's type, as a reader would think of it.
function typeOf(param) {
  switch (param.kind) {
    case "enum":
      return param.values ? `${param.enum} (${param.values.join(", ")})` : param.enum;
    case "literal":
      return param.values.map((value) => `"${value}"`).join(" \\| ");
    case "lines":
      return param.itemKind === "number" ? "number[]" : "string[]";
    case "longText":
    case "text":
      return "string";
    case "date":
      return "date (YYYY-MM-DD)";
    case "datetime":
      return "Date or ISO string";
    case "options":
      return "object";
    case "json":
      return "object (see example)";
    case "period":
      return "period";
    default:
      return param.kind;
  }
}

const cell = (value) => text(value).replace(/\|/g, "\\|").replace(/\n/g, " ");

// Every param, with an options object's fields listed as options.field.
function rows(params, prefix = "") {
  return params.flatMap((param) => {
    const name = prefix + param.name;
    const row = `| \`${name}\` | ${cell(typeOf(param))} | ${param.required ? "yes" : ""} | ${cell(param.hint ?? (param.kind === "options" ? "Only the fields you set are sent." : param.label))} |`;

    return param.kind === "options" ? [row, ...rows(param.fields ?? [], `${name}.`)] : [row];
  });
}

const versions = readdirSync(catalogs)
  .filter((file) => file.endsWith(".json"))
  .map((file) => file.replace(/\.json$/, ""));

for (const version of versions) {
  const catalog = JSON.parse(readFileSync(`${catalogs}/${version}.json`, "utf8"));
  writeResources(version, catalog);
}

writeChangelog();

function writeResources(version, catalog) {
  // Folders can't keep the dot in a URL ("0.1" becomes "01"), so every page sets its slug.
  const dir = `${root}/${version}/resources`;

  // Start clean, so a resource removed from the SDK loses its page too.
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });

  for (const resource of catalog.resources) {
    writeFileSync(`${dir}/${title(resource.name)}.mdx`, resourcePage(version, resource));
  }

  console.log(`Wrote ${catalog.resources.length} pages to ${dir}`);
}

function resourcePage(version, resource) {
  const lines = [
    "---",
    `title: ${title(resource.name)}`,
    `description: ${JSON.stringify(resource.summary)}`,
    `slug: sdk/typescript/${version}/resources/${resource.name.toLowerCase()}`,
    "layout: /src/layouts/documentation.astro",
    "---",
    "",
    "{/* Generated by scripts/generate-sdk-pages.mjs from the SDK catalog. Don't edit by hand. */}",
    "",
    "import SdkExplorer from '@/components/SdkExplorer/SdkExplorer.astro';",
    "import ScopePill from '@/components/ScopePill/ScopePill.astro';",
    "",
    text(resource.summary),
    "",
  ];

  if (resource.call === "function") {
    lines.push(`Import from \`${resource.module}\`: these are functions that take the client first.`, "");
  }

  for (const method of resource.methods) {
    lines.push(
      `## ${method.name}`,
      "",
      `\`${signature(resource, method)}\``,
      "",
      text(method.summary),
      "",
    );

    const notes = [];
    if (method.scopes.length) notes.push(`**Scopes:** ${method.scopes.map((scope) => `<ScopePill scope="${scope}" />`).join(" ")}`);
    if (method.destructive) notes.push("**Deletes data.** The explorer previews the request without sending it.");
    else if (method.writes) notes.push("**Changes data.** The explorer previews the request without sending it.");
    if (notes.length) lines.push(notes.join(" · "), "");

    if (method.params.length) {
      lines.push("| Parameter | Type | Required | Notes |", "|---|---|---|---|", ...rows(method.params), "");
    }

    lines.push(`<SdkExplorer method="${resource.name}.${method.name}" version="${version}" compact />`, "");
  }

  return lines.join("\n");
}

// The changelog page, from CHANGELOG.md. Its own title becomes the page title.
function writeChangelog() {
  const source = readFileSync("src/components/SdkExplorer/CHANGELOG.md", "utf8");
  let fenced = false;

  const body = source
    .replace(/^# .*\n+/, "")
    .split("\n")
    .map((line) => {
      if (line.startsWith("```")) fenced = !fenced;
      return fenced || line.startsWith("```") ? line : text(line);
    })
    .join("\n");

  const page = [
    "---",
    "title: Changelog",
    `description: "What changed in each version of the TypeScript SDK, and how to update."`,
    "slug: sdk/typescript/changelog",
    "layout: /src/layouts/documentation.astro",
    "---",
    "",
    "{/* Generated by scripts/generate-sdk-pages.mjs from the SDK's CHANGELOG.md. Don't edit by hand. */}",
    "",
    body,
  ];

  writeFileSync(`${root}/changelog.mdx`, page.join("\n"));
  console.log(`Wrote ${root}/changelog.mdx`);
}
